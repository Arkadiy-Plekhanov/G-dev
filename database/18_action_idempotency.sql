-- ============================================================
-- 18. Идемпотентность создания действия
-- ============================================================
-- ADR v2 §5 требует дословно: «идемпотентность создания действия
-- (client_request_id UNIQUE(user_id, client_request_id) -- против
-- даблтапов и офлайн-повторов)». До сих пор не была реализована.
--
-- Зачем сейчас, а не в Фазе 3, когда появится мобильный клиент: повтор
-- запроса рождает ВТОРОЕ действие с теми же качествами, и это не просто
-- лишняя строка -- оно попадает в средние оценки, в тренды, в сравнение
-- «выше/ниже обычного». То есть портит именно то, ради чего продукт
-- существует. Сделанное позже, это потребовало бы разбирать уже
-- накопившиеся дубли, а не просто добавить колонку.
--
-- Частичный уникальный индекс (WHERE client_request_id IS NOT NULL):
-- ключ необязателен, и старые записи без него не должны конфликтовать
-- друг с другом. Без WHERE все NULL считались бы различными в Postgres,
-- индекс бы работал -- но частичный честнее выражает намерение и меньше
-- по размеру.
--
-- Область уникальности -- пользователь, а не вся таблица: два человека
-- могут независимо прислать одинаковый ключ, и это не конфликт.
-- ============================================================

BEGIN;

ALTER TABLE actions ADD COLUMN IF NOT EXISTS client_request_id text;

CREATE UNIQUE INDEX IF NOT EXISTS actions_client_request_id_uq
    ON actions (user_id, client_request_id)
    WHERE client_request_id IS NOT NULL;

COMMIT;
