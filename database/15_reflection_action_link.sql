-- ============================================================
-- 15. reflections.action_id -- связка рефлексии с действием
-- ============================================================
-- §1 обратной связи: "рефлексия без качеств — отдельна, Рефлексия с
-- указанием качеств — качества регистрируются с привязкой к действию".
-- Качества по-прежнему живут ТОЛЬКО в quality_expressions, которая
-- по-прежнему жёстко привязана к action_id (NOT NULL) -- ни одна
-- аналитика (тренды, quality_stats, "как обычно/выше обычного") не
-- расщепляется на два параллельных источника. Рефлексия с указанными
-- качествами атомарно создаёт СВОЁ действие (одна транзакция) и
-- ссылается на него; рефлексия без качеств действие не создаёт вообще --
-- action_id остаётся NULL, это по-прежнему валидное, самостоятельное
-- состояние (чистая рефлексия без залогированного поступка).
--
-- ON DELETE SET NULL, не CASCADE: удаление действия не должно молча
-- стирать написанный текст рефлексии -- останется просто отвязанной.
-- ============================================================

BEGIN;

ALTER TABLE reflections ADD COLUMN action_id uuid REFERENCES actions(id) ON DELETE SET NULL;

COMMIT;
