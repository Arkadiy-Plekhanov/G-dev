-- ============================================================
-- 16. Удаление ручных полей уровня: current_level, dev_status_code
-- ============================================================
-- Оба задумывались как РУЧНЫЕ: человек сам проставлял себе уровень
-- качества (current_level 0-4) и статус развития (dev_status_code:
-- undeveloped/forming/stable/anchored). Интерфейса для этого не
-- появилось никогда -- ни одна строка фронтенда к ним не обращалась,
-- то есть у всех пользователей там навсегда оставались значения по
-- умолчанию.
--
-- Заменены вычисляемой стадией: growthStage() выводит Spark/Kindling/
-- Flame/Gem из средней оценки по реальным действиям (quality_stats).
-- Она меняется тогда, когда меняется поведение, и её не нужно
-- проставлять вручную -- то, ради чего ручные поля и задумывались,
-- теперь происходит само.
--
-- dev_status_type удаляется вместе с dev_status_code: это его пара
-- (составной внешний ключ на option_lists), в одиночку она
-- бессмысленна. Строки 'quality_dev_status' в option_lists остаются --
-- справочник дешёвый, а вычищать его пришлось бы отдельной проверкой,
-- что на него никто больше не ссылается.
--
-- Тот же приём, что и в 09_remove_is_relevant.sql: сначала снять
-- зависимости (здесь -- внешний ключ), потом дропнуть колонки.
-- Миграции 05 (создала колонки) и 08 (копировала их из старой таблицы)
-- НЕ переписываются: история остаётся правдивой, а удаление -- это
-- отдельный, более поздний шаг.
--
-- Ни один VIEW на эти колонки не ссылается (проверено: quality_stats,
-- action_stats, v_data_quality_alerts, goal_hierarchy, goal_counts),
-- поэтому пересоздавать представления, в отличие от 09, не требуется.
-- ============================================================

BEGIN;

ALTER TABLE user_qualities
    DROP CONSTRAINT user_qualities_dev_status_fk,
    DROP COLUMN dev_status_type,
    DROP COLUMN dev_status_code,
    DROP COLUMN current_level;

COMMIT;
