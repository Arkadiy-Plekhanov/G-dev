/**
 * Стадия развития качества, выведенная из РЕАЛЬНЫХ данных, а не из поля,
 * которое никто никогда не меняет.
 *
 * Раньше в интерфейсе показывался dev_status_code -- он приходит из БД со
 * значением по умолчанию 'undeveloped', PATCH для него в API есть, но UI
 * для смены не существует вообще. То есть у КАЖДОГО качества у каждого
 * пользователя навсегда было написано "undeveloped", независимо от того,
 * что человек реально делал. Показывать это как осмысленную характеристику
 * -- хуже, чем не показывать ничего.
 *
 * Теперь стадия считается из среднего по шкале роста (Spark/Kindling/
 * Flame/Gem). Это честно: значение меняется ровно тогда, когда меняется
 * поведение, и ничего не нужно проставлять вручную.
 *
 * Порог "минимум 3 проявления" здесь был раньше (тот же, что у stability
 * в quality_stats) -- и это оказалось ошибкой, пойманной по живым
 * скриншотам: у свежего аккаунта почти ВСЕ качества имеют 1-2 проявления,
 * и "not enough data yet" вставало буквально на каждой строке каждого
 * экрана -- захламляло восприятие ровно в тот момент, когда пользователь
 * только знакомится с приложением. Порог для СТАБИЛЬНОСТИ (сколько верить
 * ровности тренда) и для самой СТАДИИ (что показать как основной текст) --
 * разные вопросы: даже одно проявление -- уже реальный сигнал (оценил на
 * 4 один раз -- это не "нет информации", а ранний, но настоящий сигнал).
 * Честность про МАЛОЕ количество данных осталась -- она живёт в отдельном,
 * маленьком, вторичном тексте (stability/confidence), не блокирует больше
 * сам факт показа стадии.
 *
 * Возвращает ключ i18n или null, только если проявлений не было вообще
 * (avg_score_all_time отсутствует) -- тогда интерфейс показывает не
 * канцелярское "not enough data", а тёплую формулировку в той же
 * словарной системе, что и сами стадии (см. stats.stage.none в en.json).
 */
export function growthStage(quality) {
  const avg = quality?.avg_score_all_time
  if (avg === null || avg === undefined) return null

  const n = Number(avg)
  if (n < 1.5) return 'spark'
  if (n < 2.5) return 'kindling'
  if (n < 3.5) return 'flame'
  return 'gem'
}
