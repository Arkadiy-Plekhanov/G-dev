import { useLayoutEffect } from 'react'
import { useLocation } from 'react-router-dom'

/**
 * Сброс прокрутки в начало при переходе между экранами.
 *
 * Это НЕ правка под конкретную среду, хотя нашлась на iPhone. В любом
 * одностраничном приложении переход не перезагружает документ, поэтому
 * позиция прокрутки сохраняется от предыдущего экрана -- и если новый
 * экран короче, окно смотрит туда, где контента нет. На десктопе это
 * так же неправильно, просто выглядит безобиднее: человек оказывается
 * в середине страницы. На iOS Safari то же самое читается как «пустой
 * фон, пока не тронешь пальцем», потому что движок перерисовывает и
 * подтягивает прокрутку только по касанию.
 *
 * Найдено ручным тестированием на iPhone: так вели себя буквально все
 * переходы -- конец онбординга, сохранение действия, вкладка Goals,
 * профиль, сохранение рефлексии.
 *
 * Почему свой компонент, а не встроенный ScrollRestoration из React
 * Router: тот работает только с data-роутером (createBrowserRouter), а
 * здесь <BrowserRouter>. Проверено на react-router-dom 7.18.2.
 *
 * useLayoutEffect, а не useEffect: срабатывает ДО отрисовки, поэтому нет
 * мелькания старой позиции.
 *
 * Прокрутка живёт на окне, а не на .screen: у .screen нет ограниченной
 * высоты, поэтому объявленный там overflow-y ни на что не влияет.
 */
export default function ScrollToTop() {
  const { pathname } = useLocation()

  useLayoutEffect(() => {
    window.scrollTo(0, 0)
    // Safari на iOS не всегда реагирует на window.scrollTo, когда
    // прокручен корневой элемент -- сбрасываем и его напрямую.
    if (document.scrollingElement) document.scrollingElement.scrollTop = 0
  }, [pathname])

  return null
}
